fb=FontBuilder(1000,isTTF=True)
order=['.notdef','space']+['glyph'+str(ord(char)) for char in PATTERNS]
fb.setupGlyphOrder(order)
cmap={32:'space'}
for char in PATTERNS:
    name='glyph'+str(ord(char));cmap[ord(char)]=name
    if char.isalpha():cmap[ord(char.lower())]=name
fb.setupCharacterMap(cmap)
glyphs={'.notdef':TTGlyphPen(None).glyph(),'space':TTGlyphPen(None).glyph()}
for char,rows in PATTERNS.items():
    pen=TTGlyphPen(None)
    for row,pattern in enumerate(rows):
        for col,bit in enumerate(pattern):
            if bit=='1':
                x=50+col*100;y=(6-row)*100
                pen.moveTo((x,y));pen.lineTo((x,y+100));pen.lineTo((x+100,y+100));pen.lineTo((x+100,y));pen.closePath()
    glyphs['glyph'+str(ord(char))]=pen.glyph()
fb.setupGlyf(glyphs)
